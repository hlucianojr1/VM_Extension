# Quick-Start.ps1
# This script performs a complete build and deployment in one step

param(
    [switch]$SkipBuild,
    [switch]$InstallModules,
    [switch]$BuildOnly
)

$ErrorActionPreference = "Stop"

Write-Host ""
Write-Host "??????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "?   PowerShell DSC Quick Start Deployment                   ?" -ForegroundColor Cyan
Write-Host "?   .NET 4.8 Windows Service + ASP.NET 4.8 Web App          ?" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Check for Administrator privileges
if (-NOT ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole] "Administrator"))
{
    Write-Host "??  ERROR: This script must be run as Administrator" -ForegroundColor Red
    Write-Host ""
    Write-Host "Please:" -ForegroundColor Yellow
    Write-Host "  1. Right-click PowerShell" -ForegroundColor White
    Write-Host "  2. Select 'Run as Administrator'" -ForegroundColor White
    Write-Host "  3. Run this script again" -ForegroundColor White
    Write-Host ""
    exit 1
}

Write-Host "? Running with Administrator privileges" -ForegroundColor Green
Write-Host ""

# Get script directory
$scriptPath = Split-Path -Parent $MyInvocation.MyCommand.Path

# Step 1: Install DSC Modules (if requested)
if ($InstallModules) {
    Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host "Step 1: Installing Required PowerShell Modules" -ForegroundColor Cyan
    Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host ""
    
    $modulesToInstall = @("xWebAdministration", "PSDesiredStateConfiguration")
    
    foreach ($moduleName in $modulesToInstall) {
        Write-Host "Checking module: $moduleName..." -ForegroundColor Yellow
        $module = Get-Module -Name $moduleName -ListAvailable -ErrorAction SilentlyContinue
        
        if ($module) {
            Write-Host "  ? $moduleName is already installed (Version: $($module.Version))" -ForegroundColor Green
        } else {
            Write-Host "  Installing $moduleName..." -ForegroundColor Yellow
            try {
                Install-Module -Name $moduleName -Force -Scope AllUsers -AllowClobber
                Write-Host "  ? $moduleName installed successfully" -ForegroundColor Green
            } catch {
                Write-Host "  ??  Warning: Could not install $moduleName - $($_.Exception.Message)" -ForegroundColor Yellow
            }
        }
    }
    Write-Host ""
}

# Step 2: Build Applications
if (-not $SkipBuild) {
    Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host "Step 2: Building Applications" -ForegroundColor Cyan
    Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host ""
    
    $buildScript = Join-Path $scriptPath "Build-Applications.ps1"
    
    if (Test-Path $buildScript) {
        & $buildScript
        if ($LASTEXITCODE -ne 0) {
            Write-Host ""
            Write-Host "??  Build failed. Please check the errors above." -ForegroundColor Red
            exit 1
        }
    } else {
        Write-Host "??  Build script not found at: $buildScript" -ForegroundColor Red
        exit 1
    }
} else {
    Write-Host "??  Skipping build step (using existing binaries)" -ForegroundColor Yellow
    Write-Host ""
}

if ($BuildOnly) {
    Write-Host "? Build complete. Exiting (BuildOnly mode)." -ForegroundColor Green
    exit 0
}

# Step 3: Deploy with DSC
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 3: Deploying with PowerShell DSC" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$dscPath = Join-Path $scriptPath "DSC"
$deployScript = Join-Path $dscPath "DeployConfiguration.ps1"

if (Test-Path $deployScript) {
    # Change to DSC directory
    Push-Location $dscPath
    
    try {
        # Run deployment with automatic 'Y' response
        $env:QuickStartMode = "true"
        Write-Host "Y" | & $deployScript
        
        if ($LASTEXITCODE -ne 0) {
            Write-Host ""
            Write-Host "??  Deployment may have encountered issues. Check logs above." -ForegroundColor Yellow
        }
    } finally {
        Pop-Location
        Remove-Item Env:\QuickStartMode -ErrorAction SilentlyContinue
    }
} else {
    Write-Host "??  Deployment script not found at: $deployScript" -ForegroundColor Red
    exit 1
}

# Step 4: Verify Deployment
Write-Host ""
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "Step 4: Verifying Deployment" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

$verifyScript = Join-Path $dscPath "VerifyConfiguration.ps1"

if (Test-Path $verifyScript) {
    Start-Sleep -Seconds 3
    & $verifyScript
} else {
    Write-Host "??  Verification script not found. Skipping verification." -ForegroundColor Yellow
}

Write-Host ""
Write-Host "??????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host "?   Quick Start Deployment Complete!                        ?" -ForegroundColor Green
Write-Host "??????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host ""
Write-Host "?? What was deployed:" -ForegroundColor Cyan
Write-Host "   • Windows Service: MyWindowsService (Running)" -ForegroundColor White
Write-Host "   • Web Application: http://localhost/MyWebApp" -ForegroundColor White
Write-Host ""
Write-Host "?? Quick checks:" -ForegroundColor Cyan
Write-Host "   Service Status: Get-Service -Name 'MyWindowsService'" -ForegroundColor White
Write-Host "   Open Web App:   Start-Process 'http://localhost/MyWebApp'" -ForegroundColor White
Write-Host ""
Write-Host "?? Documentation:" -ForegroundColor Cyan
Write-Host "   See README.md for more details and troubleshooting" -ForegroundColor White
Write-Host ""

# Offer to open web browser
Write-Host "Would you like to open the web application in your browser? (Y/N)" -ForegroundColor Yellow
$response = Read-Host

if ($response -eq 'Y' -or $response -eq 'y') {
    Start-Process "http://localhost/MyWebApp"
}

Write-Host ""
Write-Host "Thank you for using PowerShell DSC Quick Start! ??" -ForegroundColor Cyan
Write-Host ""
